#!/usr/bin/env python3
"""Build Winmux's original WM mark; Python + Pillow, no fonts or network.

The two contours are shared by the vector, renderer, and raster exports.
Use --check to compare all generated artifacts without changing files.
"""
from __future__ import annotations

import argparse
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
GRAPHITE = "#151719"
MINT = "#9cceaf"
SIZES = (16, 24, 32, 48, 64, 128, 256)
# The upper M and lower W share their side strokes. The counter supplies
# the watchful expression without adding eyes or small decorative details.
OUTER = ((4, 5), (16, 11), (28, 5), (26, 23), (21, 28),
         (16, 24), (11, 28), (6, 23))
INNER = ((9, 12), (16, 15.5), (23, 12), (22, 21), (21, 22),
         (16, 18), (11, 22), (10, 21))


def contour(points: tuple[tuple[float, float], ...]) -> str:
    return "M" + " L".join(f"{x:g} {y:g}" for x, y in points) + " Z"


MARK = contour(OUTER) + " " + contour(INNER)


def raster(size: int) -> Image.Image:
    # Supersample each native size independently so small frames retain
    # clean diagonals. The final mark has no gradients or outline strokes.
    scale = size * 4 / 32
    image = Image.new("RGBA", (size * 4, size * 4), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((0, 0, size * 4 - 1, size * 4 - 1),
                           radius=7 * scale, fill=GRAPHITE)
    draw.polygon([(x * scale, y * scale) for x, y in OUTER], fill=MINT)
    draw.polygon([(x * scale, y * scale) for x, y in INNER], fill=GRAPHITE)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def artifacts() -> dict[Path, bytes]:
    png = BytesIO()
    raster(1024).save(png, format="PNG", optimize=False)
    frames = [raster(size) for size in SIZES]
    ico = BytesIO()
    frames[-1].save(ico, format="ICO", sizes=[(s, s) for s in SIZES],
                    append_images=frames[:-1])
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="1024" height="1024" role="img" aria-labelledby="title">
  <title id="title">Winmux WM mark</title>
  <rect width="32" height="32" rx="7" fill="{GRAPHITE}"/>
  <path d="{MARK}" fill="{MINT}" fill-rule="evenodd"/>
</svg>
'''
    component = f'''// Generated by scripts/generate-icon.py; edit the shared geometry there.
export type BrandMarkProps = {{ className?: string }};

/** Decorative WM monogram; pair with visible text or label the parent. */
export function BrandMark({{ className }}: BrandMarkProps) {{
  return (
    <svg
      className={{className}}
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 32 32"
      width="32"
      height="32"
      fill="currentColor"
      stroke="none"
      aria-hidden="true"
      focusable="false"
    >
      <path fillRule="evenodd" d="{MARK}" />
    </svg>
  );
}}

export default BrandMark;
'''
    return {
        ROOT / "build/icon.png": png.getvalue(),
        ROOT / "build/icon.ico": ico.getvalue(),
        ROOT / "build/brand.svg": svg.encode("utf-8"),
        ROOT / "src/BrandMark.tsx": component.encode("utf-8"),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify deterministic outputs without writing")
    args = parser.parse_args()
    mismatches = []
    for path, data in artifacts().items():
        relative = path.relative_to(ROOT).as_posix()
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                mismatches.append(relative)
            else:
                print(f"OK {relative}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(f"Wrote {relative}")
    if mismatches:
        parser.exit(1, "Outdated or missing: " + ", ".join(mismatches) + "\n")


if __name__ == "__main__":
    main()
