export type Language = 'en' | 'ru';
const storageKey = 'winmux.language';
const listeners = new Set<() => void>();
function readLanguage(): Language {
  try { return localStorage.getItem(storageKey) === 'ru' ? 'ru' : 'en'; }
  catch { return 'en'; }
}
let language: Language = readLanguage();
export function getLanguage() { return language; }
export function subscribeLanguage(listener: () => void) {
  listeners.add(listener);
  return () => { listeners.delete(listener); };
}
export function setLanguage(next: Language) {
  try { localStorage.setItem(storageKey, next); } catch { /* Still switch when storage is unavailable. */ }
  if (language === next) return;
  language = next;
  listeners.forEach(listener => listener());
}
if (typeof window !== 'undefined') window.addEventListener('storage', event => {
  if (event.key !== storageKey && event.key !== null) return;
  const next = readLanguage();
  if (next !== language) { language = next; listeners.forEach(listener => listener()); }
});
export function dateLocale() { return language === 'ru' ? 'ru-RU' : 'en-US'; }

