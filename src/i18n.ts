/** Russian source strings are stable keys; inserted user content stays untouched. */
export function t(key: string, ...values: (string | number)[]): string {
  const text = language === 'en' ? english[key] ?? key : key;
  return text.replace(/\{(\d+)\}/g, (placeholder, index: string) => String(values[Number(index)] ?? placeholder));
}
